/**
 * Pre-launch map generator. Writes src/core/stages/*.json and index.ts.
 * Usage: npm run maps            (regenerate all 20 stages + endless)
 *        npm run maps -- 7 bottom (print one candidate for preview)
 * The game never generates maps at runtime; it only loads the committed files.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isBoss, segmentCount, standardSegments } from '../src/core/difficulty';
import { generateEndlessMap, generateMap, validateMap } from '../src/core/mapgen';
import { Path } from '../src/core/path';
import type { EndlessData, StageData, TurretLayout } from '../src/core/types';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/core/stages');
const STAGES = 20;
const PER_WORLD = 10;
/** Snake speed in px/s: SPEED_BASE on stage 1, +SPEED_STEP per stage (tuned with tools/pacing-bot.ts). */
const SPEED_BASE = Number(process.env.SPEED_BASE ?? 40);
const SPEED_STEP = Number(process.env.SPEED_STEP ?? 0.2);
const GOALS = ['hostage', 'champion', 'castle', 'village', 'shrine'];

function findMap(baseSeed: number, layout: TurretLayout, balls: number) {
  for (let seed = baseSeed; seed < baseSeed + 500; seed++) {
    const map = generateMap(seed, layout);
    if (validateMap(map, balls).ok) return { seed, map };
  }
  throw new Error(`no valid map near seed ${baseSeed}`);
}

function stageTypes(n: number): StageData['snake']['types'] {
  if (n < 3) return {};
  if (n < 8) return { armored: 0.1 };
  if (n <= PER_WORLD) return { armored: 0.1, shielded: 0.06 };
  return { armored: 0.14, shielded: 0.1 };
}

if (process.argv[2]) {
  const seed = Number(process.argv[2]);
  const layout = (process.argv[3] as TurretLayout) ?? 'center';
  const map = generateMap(seed, layout);
  console.log(JSON.stringify({ ...map, validation: validateMap(map) }));
  process.exit(0);
}

mkdirSync(OUT, { recursive: true });
const ids: string[] = [];
for (let n = 1; n <= STAGES; n++) {
  const world = Math.ceil(n / PER_WORLD);
  const local = n - (world - 1) * PER_WORLD;
  const id = `w${world}-${String(local).padStart(2, '0')}`;
  const layout: TurretLayout = n % 2 === 1 ? 'center' : 'bottom';
  const { seed, map } = findMap(n * 1000 + 1, layout, segmentCount(n, 'expert') * 4);
  const length = new Path(map.path).length;
  const stage: StageData = {
    id,
    number: n,
    world,
    seed,
    boss: isBoss(n),
    turretLayout: layout,
    turret: map.turret,
    path: map.path,
    goal: { picture: GOALS[(n - 1) % GOALS.length] },
    snake: {
      segments: standardSegments(n),
      speed: Math.round((SPEED_BASE + SPEED_STEP * (n - 1)) * 10) / 10,
      hpFrontMult: 0.6,
      hpTailMult: 1.6,
      firstUpgradeAfter: 2,
      upgradeEvery: [3, 5],
      types: stageTypes(n),
    },
  };
  writeFileSync(join(OUT, `${id}.json`), JSON.stringify(stage) + '\n');
  ids.push(id);
  console.log(`${id}: seed ${seed}, ${layout}, path ${Math.round(length)}px, speed ${stage.snake.speed}`);
}

let endless: EndlessData | undefined;
for (let seed = 77; !endless; seed++) {
  const map = generateEndlessMap(seed);
  if (validateMap(map).ok) {
    endless = {
      id: 'endless',
      seed,
      turretLayout: 'center',
      turret: map.turret,
      path: map.path,
      goal: { picture: 'castle' },
    };
  }
}
writeFileSync(join(OUT, 'endless.json'), JSON.stringify(endless) + '\n');

const ident = (id: string) => id.replace('-', '_');
writeFileSync(
  join(OUT, 'index.ts'),
  `// Generated by tools/generate-maps.ts. Do not edit by hand.
import type { EndlessData, StageData } from '../types';
${ids.map((id) => `import ${ident(id)} from './${id}.json';`).join('\n')}
import endless from './endless.json';

export const STAGES = [${ids.map(ident).join(', ')}] as StageData[];
export const ENDLESS = endless as EndlessData;
`,
);
console.log('endless seed', endless.seed);
